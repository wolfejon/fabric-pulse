export function competitorPageForTheme(themeId: string): CompetitorPage | undefined {
  return DEMO_COMPETITOR_PAGES.find((p) => p.themeId === themeId)
}

export function competitorPagesForWorkload(workload: WorkloadId): CompetitorPage[] {
  return DEMO_COMPETITOR_PAGES.filter((p) => p.workload === workload)
}

export function defaultCompetitorPageForWorkload(
  workload: WorkloadId | 'all',
): CompetitorPage | undefined {
  if (workload === 'all') return DEMO_COMPETITOR_PAGES[0]
  return competitorPagesForWorkload(workload)[0] ?? DEMO_COMPETITOR_PAGES[0]
}

export function featuresForPage(page: CompetitorPage): CompetitorFeature[] {
  const ids = new Set(page.featureIds)
  return DEMO_COMPETITOR_FEATURES.filter((f) => ids.has(f.id))
}
